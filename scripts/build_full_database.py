# 既存全集 69問の読み込み
def load_zen_csv():
    questions = []
    with open("06_練習問題/練習問題_全集.csv", encoding="utf-8-sig") as f:
        reader = csv.DictReader(f)
        for row in reader:
            qid = row.get("元の問題ID") or f"ZEN-{row.get('通し番号', '0')}"
            ronten_id = row.get("論点ID", "KS01")
            ans = int(row.get("正解", "1"))
            
            expls = row.get("解説", "").split(" / ")
            srcs = row.get("根拠", "").split(" / ")
            quotes = row.get("根拠原文", "").split(" / ")
            
            # Pad if needed
            while len(expls) < 4: expls.append("解説準備中")
            while len(srcs) < 4: srcs.append("条文準拠")
            while len(quotes) < 4: quotes.append("条文原文に準拠")
            
            opts = []
            for i in range(1, 5):
                opt_text = row.get(f"肢{i}", "")
                expl_str = expls[i-1]
                
                # Determine status
                is_correct = "正:正しい" in expl_str or "正:適切" in expl_str
                status = "正" if is_correct else "誤"
                
                # Trap extraction heuristic
                trap = ""
                correct = ""
                if status == "誤":
                    # extract simple mismatch
                    if "誤り。" in expl_str:
                        reason = expl_str.split("誤り。")[1].strip()
                        correct = reason
                    elif "不適切。" in expl_str:
                        reason = expl_str.split("不適切。")[1].strip()
                        correct = reason
                    else:
                        correct = expl_str
                
                opts.append({
                    "num": i,
                    "text": opt_text,
                    "status": status,
                    "trap_phrase": trap,
                    "correct_phrase": correct,
                    "explanation": expl_str,
                    "statute": srcs[i-1] if i-1 < len(srcs) else "",
                    "quote": quotes[i-1] if i-1 < len(quotes) else "",
                    "key_point": "本試験頻出条文の要件を正確に押さえましょう。"
                })
            
            questions.append({
                "id": qid,
                "num": len(questions) + 1,
                "dept": row.get("部", ""),
                "ronten_id": ronten_id,
                "ronten_name": TAX_NAMES.get(ronten_id, "標準論点"),
                "key_concept": f"{TAX_NAMES.get(ronten_id, '')} に関する重要条文・基本要件",
                "rev_id": row.get("関連改正ID", ""),
                "rev_name": f"令和8年4月1日施行改正 ({row.get('関連改正ID')})" if row.get("関連改正ID") else "",
                "question": row.get("問題文", ""),
                "answer": ans,
                "options": opts
            })
    return questions

