"""論点分類表 v0.2 → v1.0 を確定する(承認済みの境界修正のみを適用)。変更履歴も出力する。"""
import csv
R=list(csv.DictReader(open("02_マスターデータ/論点分類表_案_v0.2.csv",encoding="utf-8-sig")))
By={r["論点ID"]:r for r in R}
hist=[]
def chg(i,col,new,why):
    old=By[i][col]; By[i][col]=new; hist.append(["v0.2→v1.0",i,col,old,new,why])
# 1 KY03/KY09: 建替え・敷地売却の検討費用は費用の取扱いとしてKY03へ
chg("KY03","定義",By["KY03"]["定義"]+"；建替え・敷地売却の合意形成に要する調査・検討費用の取崩しの可否",
    "パイロットでSonnet/Opusが割れた2022-27-1を受け、費用の取扱いはKY03に寄せる(承認済)")
chg("KY03","含める例",By["KY03"]["含める例"]+"／建替え等の調査費用を修繕積立金から取り崩せるか",
    "同上")
chg("KY09","論点名","防災・委託契約書・規約改正その他","建替え合意形成の費用をKY03へ移したため名称から除外")
chg("KY09","含めない例",By["KY09"]["含めない例"]+"；建替え・敷地売却の調査費用の取崩し(→KY03)","同上")
# 2 MN04: 所有者不明建物管理・管理不全建物管理
chg("MN04","定義",By["MN04"]["定義"]+"；所有者不明建物管理・管理不全建物管理などの民法上の管理制度","2023-08に受け皿が無かったため(承認済)")
chg("MN04","含める例",By["MN04"]["含める例"]+"／所有者不明建物管理人・管理不全建物管理人の選任請求","同上")
# 3 EK01/EK02: 分配金取得計画はマンション等売却事業(e-Gov目次: 第三章 マンション等売却事業 第三節 分配金取得手続等 第141条〜第146条)
chg("EK02","定義",By["EK02"]["定義"]+"；分配金取得計画(e-Gov目次で第三章 マンション等売却事業に属することを確認。本文は未取得)",
    "e-Govで確認した根拠により2024-19-1の境界を確定")
chg("EK01","含めない例",By["EK01"]["含めない例"]+"；分配金取得計画(→EK02)","同上")
# 4 TH04/TH05
chg("TH04","定義",By["TH04"]["定義"]+"；会計の収支状況書面・財産の分別管理など管理事務の実施に関する義务","2025-50-2の境界。会計・財産の分別管理はTH04(承認済)")
By["TH04"]["定義"]=By["TH04"]["定義"].replace("义务","義務")
chg("TH05","含めない例",By["TH05"]["含めない例"]+"；会計の収支状況書面・財産の分別管理(→TH04)","同上")
cols=list(R[0].keys())
with open("02_マスターデータ/論点分類表.csv","w",newline="",encoding="utf-8-sig") as f:
    w=csv.writer(f); w.writerow(["バージョン"]+cols)
    for r in R: w.writerow(["v1.0"]+[r[c] for c in cols])
with open("02_マスターデータ/論点分類表_変更履歴.csv","w",newline="",encoding="utf-8-sig") as f:
    w=csv.writer(f); w.writerow(["版","論点ID","項目","変更前","変更後","理由"]); w.writerows(hist)
print(len(R),"論点 / 変更",len(hist),"件")
