def remap_exclude(text,newid):
    def rep(m):
        ids=[o2n[x] for x in re.findall(r"[A-Z]{2}\d{2}",m.group(1))]
        ids=[i for i in dict.fromkeys(ids) if i!=newid]
        return "(→"+"/".join(ids)+")" if ids else ""
    return re.sub(r"\(→([^)]*)\)",rep,text)
def uniq_join(vals,sep="；"): return sep.join(dict.fromkeys(v for v in vals if v))
