"""論点分類表 v1.1 の『案』を生成(v1.0は変更しない)。根拠: 判定者の境界提案33件+タグ付けで『なし』になった7肢。
出力: 論点分類表_案_v1.1.csv / 論点分類表_変更履歴_案_v1.1.csv / タグ付け/再タグ付け対象_v1.1案.csv"""
import csv, json, re
R=list(csv.DictReader(open("02_マスターデータ/論点分類表.csv",encoding="utf-8-sig")))
By={r["論点ID"]:r for r in R}; hist=[]
def add(i,col,txt,why,sep="；"):
    old=By[i][col]; By[i][col]=(old+sep+txt) if old else txt; hist.append(["v1.0→v1.1案",i,col,"追記",txt,why])
def ren(i,new,why):
    hist.append(["v1.0→v1.1案",i,"論点名",By[i]["論点名"],new,why]); By[i]["論点名"]=new
# 新論点MN07(受け皿なし: 2023-12,2025-12-1/3,2022-13-4)
new=dict(By["MN06"]); 
new.update({"論点ID":"MN07","論点名":"物権変動・対抗要件・即時取得・契約解除","分野":"民法・借地借家法","根拠条文":"民法(条番号は要確認)",
 "定義":"不動産・動産の物権変動と対抗要件(登記・引渡し)、即時取得、契約総則上の解除を問う",
 "含める例":"二重売買と登記／動産の即時取得／代金不払いによる売買契約の解除と第三者","含めない例":"売買契約の成立・手付・契約不適合責任(→MN01)；区分建物の登記手続(→TK01)",
 "例示問題ID(仮)":"2023-12,2025-12,2022-13","旧論点ID(v0.1)":"(新設)"})
hist.append(["v1.0→v1.1案","MN07","(新設)","","物権変動・対抗要件・即時取得・契約解除","2023-12(4肢)・2025-12-1/-3・2022-13-4に受け皿が無かったため"])
# 境界の追記(判定者提案33件の集約)
add("KS01","含めない例","一部共用部分に関する規約の設定・変更の要件(→KS04)","2019-05-4/2020-01-2/2025-03-2の境界")
add("KS04","含める例","規約の用途制限(住宅専用条項)の解釈・違反／別段の定めの可否(対象事項の論点ではなく“別段の定め”自体を問う場合)","2023-07-1、2023-04-3")
add("KS06","含めない例","占有者に関する招集通知の掲示(→KS08)","2023-07-4")
add("KS02","含める例","共用部分の利用から生じる債権を団体として行使する場合","2023-05-3")
add("TK01","含めない例","共用部分の対抗要件という実体規定(→KS01)","2025-01-3/2025-18-3")
add("SB02","含める例","シックハウス対策の換気回数基準(建築基準法上のものを含む)","2019-45-1/2022-45-4/2024-43-3")
add("SB01","含めない例","建築基準法上の荷重・構造計算の規定(→KR02)","2020-40-4")
add("SB05","含める例","連結送水管の構造・維持管理(設置基準そのものは→KR04)","2021-44-1")
add("SB05","含めない例","避難に関する法令上の定義・基準(→KR02)；避難器具の設置義務(→KR04)","2025-40-3、2022-40-3")
ren("SB04","給湯・ガス・換気・電気設備","2021-45-4(契約電力・受電)の受け皿")
add("SB04","定義","電気設備(受電方式・契約電力の区分)を含む","2021-45-4")
add("KY03","含めない例","団地型・複合用途型特有の積立区分(→KY08)","2020-26-1")
add("KY05","含めない例","災害時の緊急対応(→KY09)；工事の総会決議要件(→KY06)","2020-31-1、2022-26-3")
add("KY01","含めない例","工事の総会決議要件(→KY06)；理事会の決議方法(→KY05)","2022-26-3、2024-29-3")
add("KY06","含めない例","共用部分変更の要件そのもの(→KS02)","2024-27-1")
add("KY09","含めない例","規約改正の要否は改正対象の事項の論点へ付ける","2023-32-1〜4")
add("KY09","含める例","所在等が不明の区分所有者への対応(探索・費用請求)","2025-28-3(受け皿なし。KY01/KY05との境界は要確認)")
add("TH02","含める例","管理計画認定に伴う特例(公社の業務等)","2022-48-2")
add("TH05","含める例","関係者の責務・努力義務","2023-46-2(TH01との境界)")
add("MN04","含めない例","物権変動・対抗要件・即時取得・契約解除(→MN07)","MN07新設に伴う")
add("MN01","含めない例","物権変動・対抗要件(→MN07)","MN07新設に伴う")
rows=[r for r in R]; 
i=[r["論点ID"] for r in rows].index("MN06"); rows.insert(i+1,new)
cols=list(R[0].keys())
with open("02_マスターデータ/論点分類表_案_v1.1.csv","w",newline="",encoding="utf-8-sig") as f:
    w=csv.writer(f); w.writerow(cols); [w.writerow(["v1.1(案)"]+[r[c] for c in cols[1:]]) for r in rows]
with open("02_マスターデータ/論点分類表_変更履歴_案_v1.1.csv","w",newline="",encoding="utf-8-sig") as f:
    w=csv.writer(f); w.writerow(["版","論点ID","項目","変更前","変更後","理由"]); w.writerows(hist)
# 再タグ付け対象: 提案肢 ∪ なし ∪ MN系でキーワードに該当
F=json.load(open("02_マスターデータ/タグ付け/最終タグ.json",encoding="utf-8"))
prop={json.loads(l)["肢ID"] for l in open("02_マスターデータ/タグ付け/判定結果.jsonl",encoding="utf-8") if json.loads(l).get("境界の要検討")}
none={i for i,v in F.items() if v["論点"]=="なし"}
inp={}
for c in range(1,15):
    for l in open(f"02_マスターデータ/タグ付け/入力_{c:02d}.jsonl",encoding="utf-8"):
        x=json.loads(l); inp[x["肢ID"]]=x
kw=re.compile(r"即時取得|対抗することができ|登記|契約を解除|解除した|引渡し")
mn={i for i,v in F.items() if v["論点"].startswith("MN") and kw.search(inp[i]["肢本文"])}
kwSB={i for i,v in F.items() if v["論点"] in ("SB04","SB05","SB03") and re.search(r"kVA|電力|受電|引込",inp[i]["肢本文"])}
tgt=prop|none|mn|kwSB
print("提案肢",len(prop),"なし",len(none),"MNキーワード",len(mn),"電気キーワード",len(kwSB),"→再タグ付け対象(重複除く)",len(tgt))
with open("02_マスターデータ/タグ付け/再タグ付け対象_v1.1案.csv","w",newline="",encoding="utf-8-sig") as f:
    w=csv.writer(f); w.writerow(["肢ID","現在の論点ID","対象理由"])
    for i in sorted(tgt): w.writerow([i,F[i]["論点"],"+".join(n for n,s in [("判定者の境界提案",prop),("論点なし",none),("MN系キーワード",mn),("電気キーワード",kwSB)] if i in s)])
print("論点数(案v1.1):",len(rows),"／変更履歴",len(hist),"件")
